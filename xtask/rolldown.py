"""Pins taba-rolldown to a rolldown release.

Separate script to avoid polluting xtask with heavy dependencies for an
occasional dev task. Run it through `cargo xtask rolldown`.

All the rolldown crates need to be pinned together, including transitive ones.
"""

import json
import sys
import tomllib
from pathlib import Path
from urllib.request import urlopen

CRATE = Path(__file__).parent.parent / "crates" / "taba-rolldown"
MARKER = "AUTOGENERATED - DO NOT EDIT BELOW HERE: See `cargo xtask rolldown pin`."


def index(crate: str) -> dict:
    """Every release of a crate from the sparse index, by version."""
    # https://doc.rust-lang.org/cargo/reference/registry-index.html#index-files
    if len(crate) == 3:
        directory = f"3/{crate[0]}"
    else:
        directory = f"{crate[:2]}/{crate[2:4]}"
    with urlopen(f"https://index.crates.io/{directory}/{crate}") as response:
        return {release["vers"]: release for release in map(json.loads, response)}


def workspace(version: str) -> set[str]:
    """Every crate in rolldown's own workspace at `version`."""
    url = f"https://raw.githubusercontent.com/rolldown/rolldown/v{version}/Cargo.toml"
    with urlopen(url) as response:
        dependencies = tomllib.load(response)["workspace"]["dependencies"]
    return {
        name
        for name, spec in dependencies.items()
        if isinstance(spec, dict) and "path" in spec
    }


def oxc_requirement(release: dict) -> str | None:
    """The oxc versions a rolldown release accepts."""
    for dependency in release["deps"]:
        if dependency["name"] == "oxc" and dependency["kind"] != "dev":
            return dependency["req"]
    return None


def truncate(path: Path, content: str) -> None:
    """Truncate to the marker and append content."""
    head, marker, _autogenerated = path.read_text().partition(MARKER)
    if not marker:
        sys.exit(f"{path} has no marker: {MARKER}")
    path.write_text(head + marker + "\n" + content)


def pin(version: str) -> None:
    """Pin rolldown's crates to `version`, and oxc to what rolldown requires."""
    releases = index("rolldown")
    if version not in releases:
        sys.exit(f"rolldown {version} isn't on crates.io")
    rolldowns = workspace(version)

    # Every crate from rolldown's workspace that rolldown builds with.
    family = ["rolldown"]
    for name in family:  # Also visits crates appended mid-loop.
        for dependency in index(name)[version]["deps"]:
            if dependency["kind"] == "dev" or dependency["optional"]:
                continue
            if dependency["name"] in rolldowns and dependency["name"] not in family:
                family.append(dependency["name"])

    oxc = oxc_requirement(releases[version])
    pins = {"oxc": oxc} | {name: f"={version}" for name in sorted(family)}
    truncate(
        CRATE / "Cargo.toml",
        "".join(f'{name} = "{req}"\n' for name, req in pins.items()),
    )
    truncate(CRATE / "src" / "lib.rs", "".join(f"pub use {name};\n" for name in pins))
    print(f"pinned rolldown {version} and oxc {oxc}")


def msrv() -> None:
    """Print each rolldown release with its oxc's MSRV: rolldown declares none."""
    oxc = index("oxc")
    for version, release in index("rolldown").items():
        required = oxc_requirement(release)
        if required and not release["yanked"]:
            required = required.removeprefix("^")
            rust_version = oxc[required].get("rust_version")
            print(f"{version:<8} oxc {required:<9} msrv {rust_version} (oxc)")


match sys.argv[1:]:
    case ["pin", pin_version]:
        pin(pin_version)
    case ["msrv"]:
        msrv()
    case arguments:
        sys.exit(f"unexpected arguments {arguments}: see `cargo xtask rolldown --help`")
